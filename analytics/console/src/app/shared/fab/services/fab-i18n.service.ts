import { inject, Injectable, Optional, signal, computed, type Signal } from '@angular/core';
import { LANGUAGE_SERVICE, type ILanguageService, type SupportedLang } from '../../design/system/services/language.service';

/**
 * FabI18nService — i18n ligero del FAB, desacoplado de Transloco.
 *
 * El FAB es portable y NO debe depender de @jsverse/transloco. En su lugar
 * consume el seam opcional LANGUAGE_SERVICE del design system: si la app lo
 * provee, el idioma del FAB se sincroniza con él; si no, fallback a 'es'.
 *
 * Uso en templates:
 *   {{ i18n.t('fab.title') }}
 */
@Injectable({ providedIn: 'root' })
export class FabI18nService {
  /** Seam opcional — null cuando la app no provee LANGUAGE_SERVICE. */
  @Optional() private readonly langSvc = inject(LANGUAGE_SERVICE, { optional: true }) ?? null;

  /** Idioma activo: del seam si existe, si no 'es'. */
  readonly lang: Signal<SupportedLang> = computed(() => this.langSvc?.activeLang() ?? 'es');

  /** Diccionario es/en. */
  private readonly dict: Record<SupportedLang, Record<string, string>> = {
    es: ES,
    en: EN,
  };

  /** Traduce una clave al idioma activo (fallback a es, luego a la clave). */
  t(key: string): string {
    const dict = this.dict[this.lang()] ?? ES;
    return dict[key] ?? ES[key] ?? key;
  }
}

